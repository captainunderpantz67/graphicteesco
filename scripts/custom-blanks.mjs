#!/usr/bin/env node
// Configurator blanks: pulls Printful's public catalog for each blank we offer and writes
// src/data/configurator/blanks.ts (catalog variant id per color/size, color hex, print area).
// No token needed (the catalog is public). Re-run when adding a color or a blank.
//   node scripts/custom-blanks.mjs
import { writeFileSync } from 'node:fs';

// Launch set (rulebook R7.2: legibility beats count; Shopify caps a product at 100 variants).
// Team colors sports moms ask for first. Order = swatch order on the page.
const BLANKS = [
  {
    id: 'bc3001', name: 'Bella+Canvas 3001 tee', printful: 71, garment: 'tee',
    colors: ['White', 'Black', 'Navy', 'Athletic Heather', 'Dark Grey Heather', 'Red', 'True Royal', 'Kelly', 'Maroon', 'Team Purple', 'Gold', 'Forest'],
    sizes: ['XS', 'S', 'M', 'L', 'XL', '2XL', '3XL'],
    // Printful's front/back DTG print area on the 3001 is 12 x 16 in; we render at 300 dpi = 3600 x 4800 px.
    printArea: { widthIn: 12, heightIn: 16 },
  },
];

const out = [];
for (const b of BLANKS) {
  const res = await fetch(`https://api.printful.com/products/${b.printful}`, { headers: { 'User-Agent': 'gtc-configurator' } });
  if (!res.ok) throw new Error(`Printful catalog ${b.printful}: ${res.status}`);
  const { result } = await res.json();
  const colors = b.colors.map((name) => {
    const vs = result.variants.filter((v) => v.color === name);
    if (!vs.length) throw new Error(`${b.name}: color "${name}" not in the catalog`);
    const sizes = Object.fromEntries(b.sizes.filter((s) => vs.some((v) => v.size === s && v.in_stock)).map((s) => [s, vs.find((v) => v.size === s).id]));
    return { name, hex: vs[0].color_code, sizes };
  });
  out.push({ id: b.id, name: b.name, printful: b.printful, garment: b.garment, printArea: b.printArea, sizes: b.sizes, colors });
  console.log(`${b.name}: ${colors.length} colors, ${colors.reduce((n, c) => n + Object.keys(c.sizes).length, 0)} variants`);
}
writeFileSync(new URL('../src/data/configurator/blanks.ts', import.meta.url),
  '// Generated by scripts/custom-blanks.mjs from Printful\'s public catalog. Do not edit by hand.\n' +
  'export interface BlankColor { name: string; hex: string; sizes: Record<string, number> } // size -> Printful catalog variant id\n' +
  'export interface Blank { id: string; name: string; printful: number; garment: string; printArea: { widthIn: number; heightIn: number }; sizes: string[]; colors: BlankColor[] }\n' +
  'export const blanks: Blank[] = ' + JSON.stringify(out, null, 1) + ';\n');
console.log('wrote src/data/configurator/blanks.ts');
