#!/usr/bin/env python3
"""Configurator fonts: the site's woff2 files -> TTF copies (for the server-side print renderer, which can't read
woff2) + a glyph-advance table so the browser preview and the print file fit text identically without measuring.
Usage: python3 scripts/custom-fonts.py
Writes public/custom/fonts/<name>.ttf and src/lib/configurator/metrics.ts (checked in; re-run only when a font changes)."""
import json, pathlib
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'public/fonts'
OUT = ROOT / 'public/custom/fonts'
OUT.mkdir(parents=True, exist_ok=True)
# role -> (woff2 file, family name the SVG uses). Families match global.css @font-face names exactly.
FONTS = {
    'display': ('big-shoulders-display-latin-900-normal.woff2', 'Big Shoulders Display'),
    'script': ('yellowtail-latin-400-normal.woff2', 'Yellowtail'),
    'body': ('archivo-latin-800-normal.woff2', 'Archivo'),
}
CHARS = [chr(c) for c in range(32, 127)] + list('’‘“”–—…áéíóúñüÁÉÍÓÚÑÜ')
metrics = {}
for role, (file, family) in FONTS.items():
    f = TTFont(SRC / file)
    f.flavor = None  # woff2 -> plain sfnt (ttf)
    ttf = OUT / f'{role}.ttf'
    f.save(ttf)
    f = TTFont(ttf)
    upm = f['head'].unitsPerEm
    cmap = f.getBestCmap(); hmtx = f['hmtx']
    adv = {}
    for ch in CHARS:
        g = cmap.get(ord(ch))
        if g: adv[ch] = round(hmtx[g][0] / upm, 4)
    os2 = f['OS/2']; hhea = f['hhea']
    metrics[role] = {
        'family': family, 'file': f'/custom/fonts/{role}.ttf', 'weight': f['OS/2'].usWeightClass,
        'ascent': round(hhea.ascent / upm, 4), 'descent': round(abs(hhea.descent) / upm, 4),
        'capHeight': round(getattr(os2, 'sCapHeight', 0) / upm, 4) or None,
        'xHeight': round(getattr(os2, 'sxHeight', 0) / upm, 4) or None,
        'advances': adv,
    }
    print(f'{role}: {family} {metrics[role]["weight"]} -> {ttf.relative_to(ROOT)} ({ttf.stat().st_size // 1024} KB, {len(adv)} glyphs)')
(ROOT / 'src/lib/configurator').mkdir(parents=True, exist_ok=True)
(ROOT / 'src/lib/configurator/metrics.ts').write_text(
    '// Generated by scripts/custom-fonts.py. Glyph advance widths (em units) for the configurator fonts.\n'
    "// Preview and print file fit text with these numbers, so both shrink a long name identically.\n"
    'export interface FontMetrics { family: string; file: string; weight: number; ascent: number; descent: number; capHeight: number | null; xHeight: number | null; advances: Record<string, number> }\n'
    'export const metrics: Record<string, FontMetrics> = ' + json.dumps(metrics, separators=(',', ':'), ensure_ascii=False) + ';\n')
print('wrote src/lib/configurator/metrics.ts')
